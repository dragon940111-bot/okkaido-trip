def altbook_html(open_=False):
    """미리 할 것 아래에 넣을 HTML (기본 접힘, 안에서 묶음별로 또 접힘)."""
    E = _h.escape
    kc = dict(ALTBOOK_KINDS)
    n = sum(len(g['items']) for g in ALTBOOK)
    legend = ''.join(f'<span class="abk k-{c}">{E(k)}</span>' for k, c in ALTBOOK_KINDS)
    grps = []
    for g in ALTBOOK:
        lis = []
        for x in g['items']:
            link = f' <a class="lnk" href="{E(x["url"])}" target="_blank" rel="noopener">가게 페이지</a>' if x.get('url') else ''
            note = f'<p class="abnote">{E(x["note"])}</p>' if x.get('note') else ''
            lis.append(f'<li class="abi"><div class="abh"><span class="abk k-{kc[x["kind"]]}">{E(x["kind"])}</span>'
                       f'<b class="jn" lang="ja">{E(x["name"])}</b><span class="abko"><span class="nml">한글 이름</span>{E(x["ko"])}</span></div>'
                       f'<p class="abslot">{E(x["slot"])}</p><p class="abhow">{x["how_html"]}{link}</p>{note}</li>')
        go = f' <a class="lnk abgo" href="{g["anchor"]}">일정 보기</a>' if g.get('anchor') else ''
        grps.append(f'<details class="abgrp" id="ab-{g["group_key"]}"><summary><b>{E(g["group_title"])}</b><span class="abn">{len(g["items"])}곳</span></summary>'
                    f'<p class="absub">{E(g["group_sub"])}{go}</p><ul class="ablist">{"".join(lis)}</ul></details>')
    return (f'<details class="altbook" id="altbook"{" open" if open_ else ""}><summary><b>{E(ALTBOOK_TITLE)}</b><span class="abcnt">{len(ALTBOOK)}묶음 · {n}곳</span></summary>'
            f'<div class="abbody"><p class="abintro">{E(ALTBOOK_INTRO)}</p><p class="abkinds">{legend}</p>{"".join(grps)}</div></details>')
